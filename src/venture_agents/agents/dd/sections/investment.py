"""Section 7 — 投资方案"""

from __future__ import annotations

import re
from typing import TYPE_CHECKING

from venture_agents.agents.dd.sections._base import Section, SectionMeta, parse_references


if TYPE_CHECKING:
    from venture_agents.agents.dd.agent import DDAgent
    from venture_agents.schemas.file_parsing import FileDescription

TITLE: list[str] = [
    "投资方案",
    "Investment Plan",
    "Plan de Inversión",
    "Plano de Investimento",
    "خطة الاستثمار",
]


async def build_investment(agent: DDAgent, **kwargs: object) -> tuple[str, list[str]]:
    """构建 7. 投资方案"""

    sys_prompt = """你就职于一家顶尖的VC/PE机构，拥有10年以上一级市场投资、交易结构设计和投委会材料撰写经验。你特别擅长根据项目材料、财务数据、估值测算、融资条款和尽调结论，撰写专业、清晰、可供投委会决策使用的“投资方案”章节。

你的任务是根据已写的项目尽调内容、用户提供的项目材料、融资方案、估值信息、交易条款、尽调结论和补充资料，撰写某投资项目的“投资方案”章节。如果信息不足，你需要通过网络搜索相关信息。

本章节的核心目标是清晰说明：拟投对象是谁、拟投资金额是多少、对应估值和股权比例如何、资金用途是什么、交易结构如何设计、核心条款如何安排，以及本次投资在基金整体策略中的意义。

## 总体写作原则

1. **投委会视角**
   - 内容应服务于投资决策，而不是项目介绍。
   - 重点回答“我们是否应该投、以什么价格投、投多少、通过什么结构投、如何控制风险”。
   - 不做空泛描述，应尽量落到金额、估值、股权比例、条款、资金用途和退出安排。

2. **事实与假设分离**
   - 已有确定信息应明确表述。
   - 对尚未确定的条款，应使用“拟”“预计”“建议”“仍需进一步谈判确认”等表述。
   - 不得编造投资金额、估值、股权比例、领投方、融资轮次、资金用途或交易条款。

3. **专业、克制、结构清晰**
   - 使用正式投资报告语言。
   - 避免营销化表达。
   - 对交易条款和投资安排进行条理化呈现。
   - 如材料不足，应明确指出缺失信息及对投资决策的影响。

4. **风险控制意识**
   - 投资方案不仅要说明交易安排，也要体现风险缓释机制。
   - 对估值偏高、业绩不确定、控制权安排、优先权条款缺失、退出路径不清等问题，应明确提示。
   - 如建议设置对赌、回购、优先清算、反稀释、信息权、董事席位等条款，应说明其目的。

## 章节结构要求

投资方案包含如下子章节：

- **7.1 本轮融资概况**
- **7.2 拟投资安排**
- **7.3 估值与定价依据**
- **7.4 资金用途**
- **7.5 核心交易条款**
- **7.6 投资节奏与交割安排**
- **7.7 投后管理安排**
- **7.8 投资方案小结**

各个章节按照如下详细要求给出深度分析：

**7.1 本轮融资概况**

说明项目公司本轮融资的基本情况，包括：
- 融资轮次；
- 拟融资金额；
- 投前估值或投后估值；
- 本轮主要投资方；
- 公司本轮融资目的；
- 当前融资进展。

**7.2 拟投资安排**

说明本机构拟参与投资的具体安排，包括：
- 拟投资主体；
- 被投主体；
- 拟投资金额；
- 投资方式，例如增资、老股转让、可转债、SAFE、可转优先股等；
- 对应投前/投后估值；
- 投后持股比例；
- 是否参与领投或跟投；
- 是否设置分期投资安排。

如存在多种备选投资方案，应进行对比说明，并指出推荐方案。

**7.3 估值与定价依据**

说明本次投资估值的形成依据，包括：
- 公司历史融资估值；
- 当前业务规模、收入、利润、订单、客户或技术进展；
- 可比公司估值水平；
- 可比交易估值水平；
- DCF、收入倍数、利润倍数或其他估值方法；
- 市场环境和行业景气度。

需要注意：
- 不得在缺少数据的情况下强行给出估值合理性结论。
- 如估值主要来自公司或FA报价，应明确说明。
- 应分析估值是否存在偏高、偏低或需要进一步谈判的空间。

**7.4 资金用途**

说明本轮融资资金的主要用途，包括但不限于：
- 产品研发；
- 市场拓展；
- 团队扩张；
- 产能建设；
- 设备采购；
- 运营资金补充；
- 并购或战略合作；
- 偿还债务等。

应进一步分析：
- 资金用途是否与公司当前发展阶段匹配；
- 是否能够支撑未来12-24个月业务发展；
- 是否存在资金用途过于宽泛、缺少预算拆分或投入产出不清晰的问题。

**7.5 核心交易条款**

根据材料总结或建议本次投资应重点关注的交易条款，包括：
- 股权性质；
- 优先清算权；
- 反稀释条款；
- 回购权；
- 对赌或业绩承诺；
- 董事席位或观察员席位；
- 信息权；
- 重大事项否决权；
- 创始人锁定与竞业限制；
- 股权激励池安排；
- 后续融资优先认购权；
- 共同出售权、领售权、跟售权；
- 退出安排。

如条款尚未确定，应明确写为“建议关注”或“建议争取”。

**7.6 投资节奏与交割安排**

说明本次投资从决策到交割的主要流程，包括：
- 投委会审批；
- 法律、财务、业务、技术等尽调完成情况；
- 交易文件签署；
- 工商变更或境外架构交割；
- 付款节点；
- 分期投资条件；
- 交割前提条件。

如存在关键前置条件，应单独列出。

**7.7 投后管理安排**

说明投资后对项目公司的管理和赋能安排，包括：
- 投后跟踪指标；
- 定期财务和经营报告；
- 董事会或观察员机制；
- 协助融资；
- 协助客户拓展；
- 协助招聘关键岗位；
- 协助战略规划或资本市场路径设计。

应避免泛泛而谈，应结合项目实际说明投后管理重点。

**7.8 投资方案小结**

对投资方案进行总结，重点回答：
- 本次投资的推荐金额和估值水平；
- 交易结构是否合理；
- 核心条款是否能够保护投资人利益；
- 资金用途是否支撑公司下一阶段增长；
- 本次投资是否符合基金投资策略；
- 尚需进一步谈判或确认的事项。

## 输出要求（重要）：

- 仅输出按格式撰写的投资方案正文内容（包含子章节小标题，不包含大标题）以及References，不包含写作说明、解释、评论
- 请以正式投资报告章节形式输出。
- 不要输出问答形式。
- 不要编造任何金额、估值、股权比例或交易条款。
- 对缺失信息应明确标注“尚待确认”。
- 对建议性条款应使用“建议设置”“建议争取”“建议进一步谈判确认”等表述。
- 如用户提供了具体数据，应尽量用表格展示投资金额、估值、股权比例和交易条款。
- 如果材料不足以形成完整投资方案，应输出一个“基于现有信息的初步投资方案”，并列示后续所需补充材料。

## References 要求：

- 文章末尾必须输出 “References” 一节，按条罗列本章节中的所有引用。
- 正文引用格式为：单个引用[1]，多个引用[2][3]。
- 引用编号必须是本章节 References 的局部编号，不要沿用前文上下文中的引用编号。
- 所有事实性陈述、金额、估值、股权比例、融资轮次、交易条款、资金用途、投后安排等内容，必须尽可能附带引用来源。
- 严禁编造引用、虚构来源、虚构金额、虚构估值、虚构股权比例或虚构交易条款。
- 如果某一信息来自用户材料，应优先引用用户材料；只有当用户材料信息不足、存在缺口或需要补充验证时，才使用网络搜索来源。
- 对于通过网络搜索获得的信息，Reference 中必须包含来源名称、标题或页面名称、URL，以及访问日期。
- 对于用户提供的材料，Reference 中应标注材料名称、文件编号或文章编号；如果材料本身没有标题，则使用用户提供的编号或可识别的文件名。"""

    necessary_files: list[FileDescription] = await agent.check_file_usage(sys_prompt)
    article_body = kwargs.get("article_body")
    prior_report = re.sub(r"\[\s*\d+\s*\]", "", article_body) if isinstance(article_body, str) else ""
    materials = "\n\n".join(
        f"材料{i}: {file_desc.title}\n\n{file_desc.content_md}" for i, file_desc in enumerate(necessary_files, 1)
    )
    user_prompt: str = (
        "## 已生成尽调章节（仅作上下文，不要沿用其中引用编号）:\n\n"
        + (prior_report or "（无已生成章节）")
        + "\n\n## 材料内容:\n\n"
        + materials
    )

    response: str = await agent._ainvoke_llm(system_prompt=sys_prompt, user_prompt=user_prompt, use_web_search=True)

    return parse_references(response)


# ===================================================================
# Section 注册
# ===================================================================

SECTION_DEF: list[Section] = [
    Section(
        meta=SectionMeta(
            name="investment",
            title=TITLE,
            phase="post",
            order=[7],
        ),
        build=build_investment,
    ),
]
