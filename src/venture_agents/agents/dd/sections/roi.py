"""Section 8 — 投资回报分析"""

from __future__ import annotations

import re
from typing import TYPE_CHECKING

from venture_agents.agents.dd.sections._base import Section, SectionMeta, parse_references


if TYPE_CHECKING:
    from venture_agents.agents.dd.agent import DDAgent
    from venture_agents.schemas.file_parsing import FileDescription

TITLE: list[str] = [
    "投资回报分析",
    "Investment Return Analysis",
    "Análisis del Retorno de Inversión",
    "Análise do Retorno do Investimento",
    "تحليل عائد الاستثمار",
]


async def build_roi(agent: DDAgent, **kwargs: object) -> tuple[str, list[str]]:
    """构建 8. 投资回报分析"""

    sys_prompt = """你就职于一家顶尖的VC/PE机构，拥有10年以上一级市场投资、财务建模、估值分析和退出回报测算经验。你特别擅长根据公司业务数据、财务预测、估值假设、退出路径和交易结构，撰写专业、审慎、可供投委会决策使用的“投资回报分析”章节。

你的任务是根据已写的项目尽调内容、用户提供的项目材料、财务数据、估值模型、融资方案、退出假设和尽调结论，撰写某投资项目的“投资回报分析”章节。如果信息不足，你需要通过网络搜索相关信息。

本章节的核心目标是分析本次投资在不同情景下的潜在回报水平，包括退出估值、退出路径、投资倍数、IRR、回本周期和主要敏感因素，并识别影响投资收益实现的关键风险。

## 总体写作原则

1. **回报测算导向**
   - 内容应围绕投资收益展开，而不是重复公司业务介绍。
   - 重点回答“投进去后可能赚多少、什么时候退出、通过什么方式退出、核心假设是否可靠”。

2. **假设透明**
   - 所有测算必须明确核心假设。
   - 应区分公司提供的预测、投资机构自行调整的预测和保守情景假设。
   - 不得编造收入、利润、估值倍数、退出时间、IRR或MOIC。
   - 如果缺少数据，应说明无法完成精确测算，并提供所需补充数据清单。

3. **情景分析**
   - 应尽量设置基准情景、乐观情景和保守情景。
   - 不应只呈现单一乐观结果。
   - 对每种情景应说明关键驱动因素和达成条件。

4. **审慎表达**
   - 避免使用“确定可实现”“必然退出”“高概率上市”等绝对化表达。
   - 应使用“预计”“假设”“在该情景下”“若公司能够实现”等表述。
   - 对高度依赖外部市场环境的退出假设，应提示不确定性。

5. **投资决策视角**
   - 不仅呈现测算结果，还要解释测算结果对投资决策的意义。
   - 应判断当前估值是否为投资人保留足够安全边际。
   - 应分析下行风险是否可接受，以及上行收益是否足够补偿风险。

## 章节结构要求

请按照以下结构撰写“投资回报分析”章节：

投资回报分析包含如下子章节：

- **8.1 回报测算基础**
- **8.2 核心财务预测假设**
- **8.3 退出路径假设**
- **8.4 退出估值假设**
- **8.5 情景回报测算**
- **8.6 敏感性分析**
- **8.7 安全边际分析**
- **8.8 主要回报风险**
- **8.9 投资回报分析小结**

各个章节按照如下详细要求给出深度分析：

**8.1 回报测算基础**

说明本次投资回报测算所依据的基础信息，包括：
- 本机构拟投资金额；
- 投前估值和投后估值；
- 投后持股比例；
- 投资工具或股权性质；
- 预计投资期限；
- 退出时间假设；
- 是否考虑后续稀释；
- 是否考虑分红、回购、优先清算等特殊条款。

**8.2 核心财务预测假设**

总结用于回报测算的公司经营预测，包括：
- 收入预测；
- 毛利率；
- EBITDA或净利润；
- 现金流；
- 客户增长；
- 订单增长；
- 产能释放；
- 费用率变化；
- 研发投入；
- 资本开支。

需要说明：
- 哪些预测来自公司管理层；
- 哪些预测经过投资机构调整；
- 哪些预测缺乏外部验证；
- 哪些指标是影响估值和退出回报的关键变量。

**8.3 退出路径假设**

分析本项目可能的退出方式，包括：
- IPO退出；
- 并购退出；
- 老股转让；
- 股东回购；
- 后续融资退出；
- 战略投资人收购。

对每种退出路径应分析：
- 可行性；
- 预计时间；
- 对公司经营规模和盈利能力的要求；
- 对资本市场环境或产业买方的依赖；
- 潜在不确定性。

如IPO或并购假设缺少支撑，应明确说明仍需进一步验证。

**8.4 退出估值假设**

说明退出估值的测算方法，包括：
- 收入倍数法；
- EBITDA倍数法；
- 净利润PE倍数法；
- DCF法；
- 可比公司估值；
- 可比交易估值；
- 最近一轮融资估值；
- 战略收购溢价假设。

需要注意：
- 应明确使用的估值倍数和依据。
- 不得在没有可比公司或交易数据的情况下声称估值合理。
- 如果估值高度依赖未来业绩，应提示业绩兑现风险。

**8.5 情景回报测算**

至少设置以下三种情景：

1. 基准情景
说明在公司基本完成经营计划、估值倍数处于合理区间、退出时间符合预期的情况下：
- 退出估值；
- 本机构退出金额；
- 投资倍数；
- IRR；
- 主要达成条件。

2. 乐观情景
说明在公司收入增长超预期、利润率提升、估值倍数上行或退出时间提前的情况下：
- 退出估值；
- 本机构退出金额；
- 投资倍数；
- IRR；
- 上行空间来源。

3. 保守情景
说明在公司增长低于预期、估值倍数下行、融资稀释加大或退出延迟的情况下：
- 退出估值；
- 本机构退出金额；
- 投资倍数；
- IRR；
- 下行风险来源。

如数据不足以计算具体IRR和投资倍数，应输出定性分析，并明确所需补充数据。

**8.6 敏感性分析**

分析影响投资回报的关键变量，包括：
- 收入增长率；
- 净利润率或EBITDA率；
- 退出估值倍数；
- 退出时间；
- 后续融资稀释；
- 本轮进入估值；
- 回购条款执行情况；
- IPO或并购市场环境。

如有数据支持，应以表格展示不同估值倍数和退出年份下的MOIC/IRR变化。

**8.7 安全边际分析**

分析本次投资价格是否具有安全边际，包括：
- 当前估值与公司现有经营规模是否匹配；
- 当前估值与可比公司/可比交易相比是否合理；
- 未来业绩增长是否已经被充分计入估值；
- 即使公司仅实现部分经营目标，投资人是否仍有合理回报；
- 下行情景下本金保护机制是否充分。

**8.8 主要回报风险**

识别影响投资回报实现的主要风险，包括：
- 业绩不达预期；
- 商业化进展低于预期；
- 竞争加剧导致估值倍数下降；
- 毛利率或费用率恶化；
- 后续融资稀释；
- 退出市场窗口关闭；
- IPO审核或并购交易不确定；
- 回购条款不可执行；
- 核心客户流失；
- 政策或监管变化。

每项风险应说明其对投资回报的具体影响，而不是简单罗列。

**8.9 投资回报分析小结**

综合判断本项目的投资回报吸引力，重点回答：
- 基准情景下是否达到基金回报要求；
- 乐观情景是否具备足够上行空间；
- 保守情景下下行风险是否可控；
- 当前估值是否为投资人保留足够安全边际；
- 退出路径是否清晰；
- 哪些核心假设需要在投前进一步验证。

## 输出要求（重要）：

- 仅输出按格式撰写的投资回报分析正文内容（包含子章节小标题，不包含大标题）以及References，不包含写作说明、解释、评论
- 请以正式投资报告章节形式输出。
- 不要输出问答形式。
- 不要编造财务预测、估值倍数、IRR、MOIC或退出时间。
- 所有测算结果必须基于用户提供的数据或明确列示的假设。
- 如材料不足，应明确说明无法完成精确测算，并列出所需补充数据。
- 如用户提供Excel、财务模型或估值表，应优先引用其中数据，并保持口径一致。
- 建议使用表格呈现：
  - 核心测算假设；
  - 三种情景回报结果；
  - 敏感性分析；
  - 关键风险与影响。
- 对公司管理层提供的预测，应保持审慎，不应直接作为投资机构结论。

## References 要求：

- 文章末尾必须输出 “References” 一节，按条罗列本章节中的所有引用。
- 正文引用格式为：单个引用[1]，多个引用[2][3]。
- 引用编号必须是本章节 References 的局部编号，不要沿用前文上下文中的引用编号。
- 所有事实性陈述、财务预测、估值倍数、退出路径、IRR、MOIC、退出时间、敏感性分析和情景假设，必须尽可能附带引用来源。
- 严禁编造引用、虚构来源、虚构财务预测、虚构估值倍数、虚构IRR、虚构MOIC或虚构退出时间。
- 如果某一信息来自用户材料，应优先引用用户材料；只有当用户材料信息不足、存在缺口或需要补充验证时，才使用网络搜索来源。
- 对于通过网络搜索获得的信息，Reference 中必须包含来源名称、标题或页面名称、URL，以及访问日期。
- 对于用户提供的材料，Reference 中应标注材料名称、文件编号或文章编号；如果材料本身没有标题，则使用用户提供的编号或可识别的文件名。"""

    necessary_files: list[FileDescription] = await agent.check_file_usage(sys_prompt)
    article_body = kwargs.get("article_body")
    prior_report = re.sub(r"\[\s*\d+\s*\]", "", article_body) if isinstance(article_body, str) else ""
    materials = "\n\n".join(
        f"材料{i}: {file_desc.title}\n\n{file_desc.content_md}" for i, file_desc in enumerate(necessary_files, 1)
    )
    user_prompt: str = (
        "## 已生成尽调章节（仅作上下文，不要沿用其中引用编号）:\n\n"
        + (prior_report or "（无已生成章节）")
        + "\n\n## 材料内容:\n\n"
        + materials
    )

    response: str = await agent._ainvoke_llm(system_prompt=sys_prompt, user_prompt=user_prompt, use_web_search=True)

    return parse_references(response)


